import os
import sys
import shutil
import tempfile

# Ensure project root is in sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from node.config import NodeConfig
from node.storage.database import Database
from node.storage.reputation import ReputationManager
from node.engine.leader import LeaderManager


def test_leader_leases_and_impeachment():
    """Verify leader leases, round-robin election, heartbeats, and follower impeachment."""
    temp_dir = tempfile.mkdtemp()
    db_path = os.path.join(temp_dir, "leader_test.db")
    try:
        os.environ["NODE_ID"] = "fednode-0"
        cfg = NodeConfig()
        cfg.node_id = "fednode-0"
        db = Database(db_path)
        rep = ReputationManager(db)
        leader = LeaderManager(cfg, rep)

        # 1. Deterministic Round-Robin Leader Selection
        # Epoch 1 -> fednode-0, Epoch 2 -> fednode-1, Epoch 3 -> fednode-2
        assert leader.get_leader_for_epoch(1) == "fednode-0"
        assert leader.get_leader_for_epoch(2) == "fednode-1"
        assert leader.get_leader_for_epoch(3) == "fednode-2"
        print("  [PASS] 1. Deterministic round-robin leader election verified (epoch % N)")

        # 2. Leader Lease Status
        assert leader.is_current_leader() is True
        print("  [PASS] 2. fednode-0 active leader lease verified for Epoch 1")

        # 3. Heartbeat generation
        hb = leader.generate_heartbeat()
        assert hb.leader_id == "fednode-0"
        assert hb.epoch == 1
        assert len(hb.signature) > 0
        print("  [PASS] 3. Signed heartbeat pulse successfully generated by leader")

        # 4. Emergency Impeachment Request
        # Follower creates impeachment when leader is unresponsive or censoring
        imp_req = leader.create_impeachment_request(justification="Leader unresponsive to reported attack")
        assert imp_req.leader_id == "fednode-0"
        assert imp_req.target_epoch == 1
        assert imp_req.accuser_id == "fednode-0"
        print("  [PASS] 4. Follower impeachment request created with cryptographic audit")

    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


if __name__ == "__main__":
    print("\n=======================================================")
    print("   PHASE 2 FACTOR: LEADER LEASES & IMPEACHMENT ENGINE  ")
    print("=======================================================")
    test_leader_leases_and_impeachment()
    print("=======================================================")
    print("   ALL LEADER ELECTION MODULES PASS 100%!              ")
    print("=======================================================\n")
